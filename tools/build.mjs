// Encrypts the board's private config into payload.js.
//
//   node tools/build.mjs            (reads tools/config.local.json)
//
// config.local.json is git-ignored and must never be committed: it holds the
// staff password and the Clappia embed links. Only the encrypted payload.js
// is published.
//
// config.local.json shape:
// {
//   "password": "staff password",
//   "title": "Hottie Check-In Board",
//   "refreshSeconds": 60,
//   "log":    { "title": "Check-in log", "embed": "<iframe src=...> or a URL" },
//   "charts": [ { "title": "Check-ins by day", "embed": "<iframe ...>", "wide": false } ]
// }

import { readFileSync, writeFileSync } from 'node:fs';
import { webcrypto as crypto } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const cfgPath = process.argv[2] || join(here, 'config.local.json');
const cfg = JSON.parse(readFileSync(cfgPath, 'utf8'));
if (!cfg.password || cfg.password.length < 10) {
  console.error('Set a password of at least 10 characters in config.local.json');
  process.exit(1);
}

const srcOf = (embed) => {
  if (!embed) return null;
  const m = String(embed).match(/src\s*=\s*["']([^"']+)["']/i);
  const url = (m ? m[1] : String(embed)).trim().replace(/&amp;/g, '&');
  if (!/^https:\/\//i.test(url)) throw new Error('Embed is not an https URL or iframe: ' + embed);
  return url;
};

const publicCfg = {
  title: cfg.title || 'Check-In Board',
  refreshSeconds: cfg.refreshSeconds ?? 60,
  log: cfg.log ? { title: cfg.log.title || 'Check-in log', src: srcOf(cfg.log.embed) } : null,
  charts: (cfg.charts || []).map(c => ({ title: c.title || 'Chart', src: srcOf(c.embed), wide: !!c.wide })),
  sheet: cfg.sheet ? { csv: srcOf(cfg.sheet.csv), aliases: cfg.sheet.aliases ? srcOf(cfg.sheet.aliases) : null } : null,
  app: cfg.app ? { title: cfg.app.title || 'Check in', src: srcOf(cfg.app.embed) } : null,
};

const ITER = 600000;
const enc = new TextEncoder();
const salt = crypto.getRandomValues(new Uint8Array(16));
const iv = crypto.getRandomValues(new Uint8Array(12));
const base = await crypto.subtle.importKey('raw', enc.encode(cfg.password.normalize('NFC').replace(/[\u2018\u2019\u02BC\u2032]/g, "'").replace(/[\u201C\u201D]/g, '"')), 'PBKDF2', false, ['deriveBits']);
const raw = new Uint8Array(await crypto.subtle.deriveBits({ name: 'PBKDF2', hash: 'SHA-256', salt, iterations: ITER }, base, 256));
const key = await crypto.subtle.importKey('raw', raw, 'AES-GCM', false, ['encrypt']);
const data = new Uint8Array(await crypto.subtle.encrypt({ name: 'AES-GCM', iv }, key, enc.encode(JSON.stringify(publicCfg))));

const b64 = (u8) => Buffer.from(u8).toString('base64');
const out = `// Generated by tools/build.mjs. Encrypted; safe to publish.\nwindow.PAYLOAD = ${JSON.stringify({ v: 1, iterations: ITER, salt: b64(salt), iv: b64(iv), data: b64(data) })};\n`;
writeFileSync(join(here, '..', 'payload.js'), out);
console.log(`payload.js written: log=${!!publicCfg.log}, charts=${publicCfg.charts.length}, refresh=${publicCfg.refreshSeconds}s`);
